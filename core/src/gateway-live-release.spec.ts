type Docs = Record<string, Record<string, unknown>>;

function database(docs: Docs) {
  return {
    doc(path: string) {
      const data = docs[path];
      return {
        get: async () => ({
          exists: data !== undefined,
          data: () => data,
        }),
      };
    },
  };
}

function mutableConfig(
  overrides: Partial<GatewayMutableConfig> = {},
): GatewayMutableConfig {
  return {
    configSchemaVersion: 1,
    profile: "builder",
    gatewayClass: "builder",
    imageProfile: "builder",
    sizingTier: "l",
    gcpProject: null,
    gatewayContainerSecurityContext: null,
    serviceAccountName: null,
    serviceAccount: null,
    builderAccess: { controlUiEnabled: true },
    ownerUid: "uid-ceckert",
    builderSlug: "ceckert",
    openclawOverrides: null,
    modelBrokerLimits: null,
    preemption: null,
    ...overrides,
  };
}

function durableGateway(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    gatewayId: "bender",
    latestRelease: 2,
    desiredRelease: 2,
    liveRelease: 2,
    desiredStatus: "running",
    ...mutableConfig(),
    ...overrides,
  };
}

function servingRuntime(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    docKind: "runtime",
    gatewayId: "bender",
    release: 2,
    lifecycle: "serving",
    heartbeat: { status: "ready" },
    ...overrides,
  };
}

describe("initialGatewayReleaseDocuments", () => {
  it("materializes one durable root and its immutable first release", () => {
    const config = mutableConfig({
      profile: null,
      gatewayClass: "shared",
      imageProfile: "standard",
      sizingTier: null,
      builderAccess: null,
      ownerUid: null,
      builderSlug: null,
    });
    const result = initialGatewayReleaseDocuments({
      gatewayId: "default",
      config,
      artifact: {
        imageRepository: "us-west1-docker.pkg.dev/octogee/octogee/octogee-gateway",
        imageTag: "753c212",
      },
      createdBy: "glm-controller-bootstrap",
      now: 42,
      desiredStatus: "running",
    });

    expect(result.gatewayDoc).toMatchObject({
      gatewayId: "default",
      latestRelease: 1,
      desiredRelease: 1,
      liveRelease: null,
      desiredStatus: "running",
      gatewayClass: "shared",
    });
    expect(result.releaseDoc).toMatchObject({
      gatewayId: "default",
      release: 1,
      sourceRelease: null,
      payload: {
        imageRepository: "us-west1-docker.pkg.dev/octogee/octogee/octogee-gateway",
        imageTag: "753c212",
      },
    });
    expect(result.releaseDoc.payloadHash).toBe(
      releasePayloadHash(result.releaseDoc.payload),
    );
  });
});

describe("gateway durable configuration authorization", () => {
  it("authorizes a durable root document without issuing a second Firestore read", () => {
    expect(gatewayAuthorizationFromRootDocument(durableGateway(), "bender")).toMatchObject({
      kind: "durable",
      gateway: { gatewayId: "bender" },
      config: { ownerUid: "uid-ceckert" },
    });
    expect(gatewayAuthorizationFromRootDocument(durableGateway(), "other")).toBeNull();
  });

  it("authorizes an empty retired co-owner mirror without exposing it as mutable config", () => {
    const authorization = gatewayAuthorizationFromRootDocument(
      durableGateway({ coOwnerUids: [] }),
      "bender",
    );

    expect(authorization).toMatchObject({
      kind: "durable",
      gateway: { gatewayId: "bender" },
      config: { ownerUid: "uid-ceckert" },
    });
    expect(authorization?.config).not.toHaveProperty("coOwnerUids");
    expect(
      gatewayAuthorizationFromRootDocument(
        durableGateway({ coOwnerUids: ["uid-former-helper"] }),
        "bender",
      ),
    ).toBeNull();
  });

  it("rejects revision-shaped ids before attempting a durable root read", async () => {
    let reads = 0;
    const db = {
      doc() {
        reads += 1;
        throw new Error("revision ids must not reach Firestore");
      },
    };

    expect(isBareGatewayId("bender")).toBe(true);
    expect(isBareGatewayId("bender-r2")).toBe(false);
    await expect(readGatewayAuthorization(db as never, "bender-r2")).resolves.toBeNull();
    expect(reads).toBe(0);
  });

  it("uses root mutable configuration instead of stale bare glm gateway config", async () => {
    const docs: Docs = {
      "gateways/bender": durableGateway(),
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payload: {
          gatewayClass: "shared",
          ownerUid: "uid-someone-else",
          builderAccess: { controlUiEnabled: false },
        },
      },
      "glmGateways/bender": servingRuntime(),
    };

    await expect(readGatewayAuthorization(database(docs) as never, "bender")).resolves.toMatchObject({
      kind: "durable",
      config: {
        gatewayClass: "builder",
        ownerUid: "uid-ceckert",
        builderAccess: { controlUiEnabled: true },
      },
    });
    await expect(readServingGatewayAuthorization(database(docs) as never, "bender")).resolves.toMatchObject({
      kind: "durable",
      config: { gatewayClass: "builder" },
    });
  });

  it("fails closed when the runtime doc is legacy-shaped instead of a runtime record", async () => {
    const docs: Docs = {
      "gateways/bender": durableGateway(),
      "glmGateways/bender": {
        gatewayId: "bender",
        ownerUid: "uid-ceckert",
        gatewayClass: "shared",
        profile: "standard",
      },
    };
    await expect(readServingGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
  });

  it("fails closed instead of falling back to stale bare glm config before the root config marker exists", async () => {
    const docs: Docs = {
      "gateways/bender": durableGateway({ configSchemaVersion: undefined }),
      "glmGateways/bender": {
        gatewayId: "bender",
        ownerUid: "uid-ceckert",
        gatewayClass: "builder",
      },
    };

    await expect(readGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
  });

  it("fails closed when no durable gateway exists instead of reading a bare glm config", async () => {
    const docs: Docs = {
      "glmGateways/bender": {
        gatewayId: "bender",
        ownerUid: "uid-ceckert",
        gatewayClass: "builder",
        builderAccess: { controlUiEnabled: true },
      },
    };

    await expect(readServingGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
  });

  it("does not authorize a runtime realization without a durable root", async () => {
    const docs: Docs = {
      "glmGateways/bender": servingRuntime({
        ownerUid: "uid-ceckert",
        gatewayClass: "builder",
      }),
    };

    await expect(readGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
  });

  it("does not revive stale legacy authority when a durable gateway doc is malformed", async () => {
    const docs: Docs = {
      "gateways/bender": { gatewayId: "bender", desiredStatus: "running" },
      "glmGateways/bender": {
        gatewayId: "bender",
        ownerUid: "uid-ceckert",
        gatewayClass: "builder",
        builderAccess: { controlUiEnabled: true },
      },
    };

    await expect(readGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
  });

  it("rejects a runtime realization that is missing or not serving", async () => {
    const docs: Docs = {
      "gateways/bender": durableGateway(),
      "glmGateways/bender": servingRuntime({ lifecycle: "failed" }),
    };

    await expect(readServingGatewayAuthorization(database(docs) as never, "bender")).resolves.toBeNull();
    await expect(
      readServingGatewayAuthorization(database({ "gateways/bender": durableGateway() }) as never, "bender"),
    ).resolves.toBeNull();
  });

  it("merges only root mutable configuration with the selected immutable artifact", () => {
    const config = {
      ...mutableConfig(),
      imageTag: "stale-tag",
    } as unknown as GatewayMutableConfig;

    const rendered = mergeGatewayConfigWithArtifact(config, {
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });

    expect(rendered).toMatchObject({
      imageTag: "deadbee",
      gatewayClass: "builder",
      ownerUid: "uid-ceckert",
    });
    expect(rendered).not.toHaveProperty("configSchemaVersion");
  });

  it("rejects invalid mutable ownership and preemption values", () => {
    expect(isGatewayMutableConfig(mutableConfig({ ownerUid: null }))).toBe(false);
    expect(isGatewayMutableConfig(mutableConfig({ coOwnerUids: [""] }))).toBe(false);
    expect(
      isGatewayMutableConfig(mutableConfig({ modelBrokerLimits: { spendWeekUsd: -1 } })),
    ).toBe(false);
    expect(isGatewayMutableConfig({ ...mutableConfig(), byosub: {} })).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "custom-operator-ksa" }),
        "bender",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gw-bender" }),
        "bender",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gateway-bender" }),
        "bender",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gw-other" }),
        "bender",
      ),
    ).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gateway-other" }),
        "bender",
      ),
    ).toBe(false);
    for (const reserved of ["octogee-api", "octogee-glm-controller", "octogee-cron", "octogee-gateway"]) {
      expect(
        isGatewayMutableConfigForGateway(mutableConfig({ serviceAccountName: reserved }), "bender"),
      ).toBe(false);
    }
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "invalid_name" }),
        "bender",
      ),
    ).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(mutableConfig({ serviceAccountName: "UPPER" }), "bender"),
    ).toBe(false);
    expect(
      isGatewayMutableConfig(mutableConfig({ serviceAccount: { create: "yes" } as never })),
    ).toBe(false);
    expect(
      isGatewayMutableConfig(
        mutableConfig({ builderAccess: { kubeApiServerEgressCidrs: ["10.0.0.0/8", 1] } as never }),
      ),
    ).toBe(false);
  });

  it("reads an artifact-only selected release", async () => {
    const docs: Docs = {
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
        },
      },
    };

    await expect(readGatewayArtifact(database(docs) as never, "bender", 2)).resolves.toEqual({
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });
  });

  it("preserves the builder package receipt when projecting a release artifact", async () => {
    const profileImages = {
      builder: {
        imageRepository:
          "us-central1-docker.pkg.dev/octogee/octogee/octogee-gateway-builder",
        imageTag: `deadbee@sha256:${"b".repeat(64)}`,
      },
    };
    const docs: Docs = {
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payload: {
          imageRepository:
            "us-central1-docker.pkg.dev/octogee/octogee/octogee-gateway",
          imageTag: `deadbee@sha256:${"a".repeat(64)}`,
          profileImages,
        },
      },
    };

    await expect(readGatewayArtifact(database(docs) as never, "bender", 2)).resolves.toMatchObject({
      profileImages,
    });
  });

  it("reads a hash-verified artifact through the retired Mac schema upgrade", async () => {
    const payload = {
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
      macOpsTokenProtocol: { version: 1 },
    };
    const docs: Docs = {
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payloadHash: releasePayloadHash(payload as never),
        payload,
      },
    };

    await expect(readGatewayArtifact(database(docs) as never, "bender", 2)).resolves.toEqual({
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });
  });

  it("refuses a release payload that still carries mutable policy or credential state", async () => {
    const docs: Docs = {
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
          gatewayClass: "shared",
          byosub: { legacy: true },
        },
      },
    };

    await expect(readGatewayArtifact(database(docs) as never, "bender", 2)).resolves.toBeNull();
  });
  it("reads heartbeat telemetry from the gateway's serving runtime doc", async () => {
    const docs: Docs = {
      "glmGateways/bender": servingRuntime({ heartbeat: { status: "ready" } }),
    };

    await expect(
      readGatewayRuntimeHeartbeat(
        database(docs) as never,
        durableGateway() as never,
      ),
    ).resolves.toEqual({ status: "ready" });
  });

  it("refuses a non-serving runtime even when its stale heartbeat says ready", async () => {
    const docs: Docs = {
      "glmGateways/bender": servingRuntime({
        lifecycle: "failed",
        heartbeat: { status: "ready" },
      }),
    };

    await expect(
      readGatewayRuntimeHeartbeat(
        database(docs) as never,
        durableGateway() as never,
      ),
    ).resolves.toBeNull();
  });

  it("refuses a release payload that still carries credential state", async () => {
    const docs: Docs = {
      "gateways/bender/releases/2": {
        gatewayId: "bender",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
          byosub: { legacy: true },
        },
      },
    };

    await expect(readGatewayArtifact(database(docs) as never, "bender", 2)).resolves.toBeNull();
  });
});
