const POD_NAME = "octogee-gateway-bender-5bc5949d46-p946t";

describe("podBelongsToGateway", () => {
  it("accepts pods generated by the gateway's stable-name Deployment", () => {
    expect(podBelongsToGateway("bender", POD_NAME)).toBe(true);
  });

  it("rejects another gateway's pods, a bare deployment name, and junk suffixes", () => {
    expect(podBelongsToGateway("bender", "octogee-gateway-other-5bc5949d46-p946t")).toBe(false);
    expect(podBelongsToGateway("bender", "octogee-gateway-bender")).toBe(false);
    expect(podBelongsToGateway("bender", "octogee-gateway-bender-")).toBe(false);
    expect(podBelongsToGateway("bender", "octogee-gateway-bender-UPPER")).toBe(false);
    expect(podBelongsToGateway("bender", undefined)).toBe(false);
  });
});

describe("configuredBuilderBootstrapAllowed", () => {
  const configured = {
    gatewayId: "bender",
    createdAt: 1,
    createdBy: "admin",
    updatedAt: 1,
    updatedBy: "admin",
    latestRelease: 2,
    desiredRelease: 2,
    liveRelease: 1,
    desiredStatus: "running",
    ...mutableConfig({ builderSlug: "alice" }),
  };

  it("allows the configured isolated builder while the gateway is running", () => {
    expect(configuredBuilderBootstrapAllowed(configured, {
      gatewayId: "bender",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(true);
    expect(configuredBuilderBootstrapAllowed(configured, {
      gatewayId: "bender",
      podName: POD_NAME,
      slug: "victim",
    })).toBe(false);
    expect(configuredBuilderBootstrapAllowed({ ...configured, gatewayId: "other" }, {
      gatewayId: "bender",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
    expect(configuredBuilderBootstrapAllowed(configured, {
      gatewayId: "bender",
      podName: "octogee-gateway-other-5bc5949d46-p946t",
      slug: "alice",
    })).toBe(false);
  });

  it.each([
    { desiredStatus: "paused" },
    { desiredStatus: "draining" },
    { desiredStatus: "retired" },
    { retireAfter: 2 },
    { retirementClaim: { operationId: "retire-1", version: 1 } },
  ])("rejects configured-builder bootstrap after lifecycle revocation: %o", (override) => {
    expect(configuredBuilderBootstrapAllowed({ ...configured, ...override }, {
      gatewayId: "bender",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
  });

  it("rejects shared gateways because they have no configured builder identity", () => {
    expect(configuredBuilderBootstrapAllowed({ ...configured, gatewayClass: "shared" }, {
      gatewayId: "bender",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
  });
});

